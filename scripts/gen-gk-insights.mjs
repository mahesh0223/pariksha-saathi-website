#!/usr/bin/env node
// Counts what SSC asked in General Awareness across every previous-year paper we publish, for the data page
// /exams/ssc-gk-topics/ (src/lib/gkInsights.mjs). Reads the server's PYQ seed files - the same files the solved papers
// come from - and writes src/data/gkInsights.mjs. Re-run and commit when papers are added:
//   node scripts/gen-gk-insights.mjs [--server <pariksha-saathi-server checkout>]
// Topics are our own tags (each question's topicKey); themes are keyword matches on the question text, so one question
// can count under two themes. Only questions published as text are counted (the few printed as images, and the rare
// question whose key we could not account for, are not in the files).
import fs from 'node:fs';
import path from 'node:path';

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : fallback;
};
const SERVER = arg('--server', '/Users/mahesh/dev/pariksha-saathi-server-wt-telegram');
const DIR = path.join(SERVER, 'prisma/seed-data/pyq');
const GA = new Set(['General Awareness', 'Part-B-General Knowledge and General awareness']);
const EXAMS = ['ssc_cgl', 'ssc_chsl', 'ssc_mts', 'ssc_gd'];
const THEMES = [
  ['awards', /award|padma|bharat ratna|puraskar|samman|khel ratna|arjuna/],
  ['dance', /\bdance|nritya|dancer/],
  ['sports', /cricket|football|hockey|olympic|tournament|trophy|cup\b|badminton|tennis|chess|kabaddi/],
  ['books', /\bauthor|book|written by|autobiography|memoir/],
  ['music', /instrument|sitar|tabla|sarod|shehnai|santoor|veena|flute|gharana|vocalist|musician|singer/],
  ['festival', /festival|\bmela\b|celebrated/],
  ['chemistry', /chemical|element|compound|acid|formula|reaction|metal/],
  ['schemes', /scheme|yojana|mission\b/],
  ['appointments', /governor|chief minister|appointed|sworn in/],
  ['constitution', /\barticle\b|schedule of the (indian )?constitution|amendment/],
  ['rivers', /\briver|\bdam\b|lake|tributar/],
  ['body', /vitamin|disease|deficiency|blood|human body|organ\b|kidney|heart/],
];
const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const generic = (a) => a.length <= 3 || /^[\d\s,.%-]+$/.test(a) || /^(all of the above|none of the above|both .*|only .*)$/i.test(a);

const topics = {};
const byExam = Object.fromEntries(EXAMS.map((e) => [e, { total: 0, topics: {} }]));
const papers = Object.fromEntries(EXAMS.map((e) => [e, new Set()]));
const answers = {};
const themes = {};
const seen = new Map();
let total = 0;
let filesRead = 0;
for (const examId of EXAMS) {
  const dir = path.join(DIR, examId);
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json') && !f.startsWith('_')).sort()) {
    const paper = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
    filesRead++;
    for (const q of paper.questions) {
      if (!GA.has(q.section) || q.cancelled) continue;
      total++;
      papers[examId].add(`${paper.paper}|${paper.date}|${paper.shift}`);
      topics[q.topicKey] = (topics[q.topicKey] ?? 0) + 1;
      byExam[examId].total++;
      byExam[examId].topics[q.topicKey] = (byExam[examId].topics[q.topicKey] ?? 0) + 1;
      const answer = q.options[q.correctOptionIndex].trim();
      if (!generic(answer)) answers[answer] = (answers[answer] ?? 0) + 1;
      const text = q.text.toLowerCase();
      for (const [key, rx] of THEMES) if (rx.test(text)) themes[key] = (themes[key] ?? 0) + 1;
      const key = `${norm(q.text)}|${norm(answer)}`;
      if (!seen.has(key)) seen.set(key, { text: q.text, answer, papers: [] });
      seen.get(key).papers.push({ examId, paper: paper.paper, date: paper.date, shift: paper.shift });
    }
  }
}
const sorted = (o) => Object.entries(o).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
const data = {
  total,
  // Every SSC paper file read, with or without a General Awareness section: check-public-pages.mjs compares it with the
  // solved-paper index so the page cannot fall behind newly added papers.
  filesRead,
  paperCount: EXAMS.reduce((n, e) => n + papers[e].size, 0),
  papersByExam: Object.fromEntries(EXAMS.map((e) => [e, papers[e].size])),
  topics: sorted(topics),
  byExam: Object.fromEntries(EXAMS.map((e) => [e, { total: byExam[e].total, topics: sorted(byExam[e].topics) }])),
  topAnswers: sorted(answers).slice(0, 15),
  themes: sorted(themes),
  repeats: [...seen.values()].filter((r) => r.papers.length > 1).sort((a, b) => b.papers.length - a.papers.length || a.text.localeCompare(b.text)),
};
const out = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/data/gkInsights.mjs');
fs.writeFileSync(out, `// Generated by scripts/gen-gk-insights.mjs from the server's PYQ seed files - do not edit by hand.\nexport const GK_INSIGHTS = ${JSON.stringify(data, null, 1)};\n`);
console.log(`${total} General Awareness questions from ${data.paperCount} papers -> ${path.relative(process.cwd(), out)}`);
