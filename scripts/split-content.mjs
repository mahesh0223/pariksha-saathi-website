// Splits the two monolithic bilingual content modules into one module per entry, so a lesson or
// job-profile page downloads only its own content:
//
//   src/data/topicLessons.mjs     (all 144 lessons, ~2.9 MB raw / 560 KB brotli)
//     -> src/data/generated/lessons/<slug>.mjs        (one lesson, both languages, ~5-10 KB brotli)
//   src/data/examJobProfiles.mjs  (all job profiles, ~250 KB raw)
//     -> src/data/generated/job-profiles/<slug>.mjs
//
// The pages import these through src/lib/contentChunks.ts (an import.meta.glob over each folder),
// so Vite emits one chunk per file, and scripts/prerender.mjs adds a <link rel="modulepreload">
// for the matching chunk to every prerendered lesson/job-profile page.
//
// The source of truth stays topicLessons.mjs / examJobProfiles.mjs (hand-edited, and what the
// prerender step and check:public read). This folder is generated - gitignored - and rebuilt by
// `npm run generate`, which `npm run build` and `npm run dev` run first; check:public fails if it
// is out of date. Stale files for removed slugs are deleted.
import { mkdirSync, readdirSync, rmSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOPIC_LESSONS } from '../src/data/topicLessons.mjs';
import { LESSON_CATALOG } from '../src/data/lessonCatalog.mjs';
import { EXAM_JOB_PROFILES } from '../src/data/examJobProfiles.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const GENERATED_DIR = join(here, '../src/data/generated');

/**
 * What a lesson's generated module carries: the entry plus the catalog's topicKey (the key the
 * practice-quiz link uses; scripts/prerender.mjs reads it from LESSON_CATALOG the same way), so the
 * page needs nothing but its own chunk - it used to pull the whole 21 KB catalog in just for this.
 */
export function lessonModuleEntry(entry) {
  const topicKey = LESSON_CATALOG.find((item) => item.slug === entry.slug)?.topicKey ?? entry.topicKey;
  return topicKey ? { ...entry, topicKey } : entry;
}

/** @returns {{ written: number, removed: number }} */
export function splitContent({ log = console.log } = {}) {
  let written = 0;
  let removed = 0;
  for (const [folder, entries, source, moduleEntry] of [
    ['lessons', TOPIC_LESSONS, 'topicLessons.mjs', lessonModuleEntry],
    ['job-profiles', EXAM_JOB_PROFILES, 'examJobProfiles.mjs', (entry) => entry],
  ]) {
    const dir = join(GENERATED_DIR, folder);
    mkdirSync(dir, { recursive: true });
    const before = { written, removed };
    const slugs = new Set();
    for (const entry of entries) {
      if (!/^[a-z0-9-]+$/.test(entry.slug)) throw new Error(`${source}: slug "${entry.slug}" is not a safe file name`);
      if (slugs.has(entry.slug)) throw new Error(`${source}: duplicate slug "${entry.slug}"`);
      slugs.add(entry.slug);
      const file = join(dir, `${entry.slug}.mjs`);
      const text = `// Generated by scripts/split-content.mjs from src/data/${source} - do not edit; edit the source and run \`npm run generate\`.\nexport default ${JSON.stringify(moduleEntry(entry), null, 2)};\n`;
      // Leave untouched files alone so Vite's dev watcher and the build cache see no change.
      if (existsSync(file) && readFileSync(file, 'utf8') === text) continue;
      writeFileSync(file, text, 'utf8');
      written += 1;
    }
    for (const name of readdirSync(dir)) {
      const slug = name.replace(/\.mjs$/, '');
      if (!name.endsWith('.mjs') || !slugs.has(slug)) {
        rmSync(join(dir, name), { recursive: true });
        removed += 1;
      }
    }
    log(`${folder}: ${entries.length} modules (${written - before.written} written, ${removed - before.removed} removed)`);
  }
  return { written, removed };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) splitContent();
