// Regenerates src/data/lessonCatalogHi.mjs from topicLessons.mjs. Run after adding or editing a lesson:
//   node scripts/gen-lesson-catalog-hi.mjs
// check-public-pages.mjs fails the build when the committed file no longer matches this derivation.
import { writeFileSync } from 'node:fs';
import { TOPIC_LESSONS } from '../src/data/topicLessons.mjs';
import { deriveHindiCatalogEntry } from '../src/lib/lessonCatalogHi.mjs';

const entries = TOPIC_LESSONS.map(deriveHindiCatalogEntry);
const body = entries.map((e) => `  ${JSON.stringify(e)},`).join('\n');
writeFileSync(
  new URL('../src/data/lessonCatalogHi.mjs', import.meta.url),
  `// GENERATED by scripts/gen-lesson-catalog-hi.mjs from topicLessons.mjs - do not hand-edit.\n` +
    `// The Hindi lesson library (/hi/learn/) lists these instead of importing the 2.4 MB lessons module;\n` +
    `// scripts/check-public-pages.mjs fails the build if this file is stale.\n` +
    `export const LESSON_CATALOG_HI = [\n${body}\n];\n`,
  'utf8',
);
console.log(`Wrote ${entries.length} Hindi catalog entries.`);
