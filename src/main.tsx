import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { BrowserRouter } from 'react-router-dom';
import { ExamSelectionProvider } from './state/ExamSelectionContext';
import { LanguageProvider } from './state/LanguageContext';
import { AuthProvider } from './state/AuthContext';
import { App, preloadRoute } from './App';
import './styles/theme.css';

const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      staleTime: 5 * 60 * 1000,
      retry: 1,
    },
  },
});

function mount() {
  createRoot(document.getElementById('root')!).render(
    <StrictMode>
      <QueryClientProvider client={queryClient}>
        <AuthProvider>
          <LanguageProvider>
            <ExamSelectionProvider>
              <BrowserRouter>
                <App />
              </BrowserRouter>
            </ExamSelectionProvider>
          </LanguageProvider>
        </AuthProvider>
      </QueryClientProvider>
    </StrictMode>,
  );
}

// On a prerendered page (/learn/*, /compare/*, /exams/*...) real content is already on screen when
// this script runs. Fetch that route's chunk first, then mount: mounting earlier would swap the
// article for a Suspense spinner until the chunk arrived. The home page and /app/* have nothing
// to preload and mount straight away. See App.tsx's preloadRoute and lib/lazyPage.ts.
preloadRoute(window.location.pathname).then(mount, mount);

// Service worker (generated by vite-plugin-pwa into dist/sw.js, see vite.config.ts). Registered
// after `load` so it never competes with the page's own requests, and only from production builds -
// `vite dev` has no sw.js. Prerendered pages run this same bundle, so they register it too.
if (import.meta.env.PROD && 'serviceWorker' in navigator) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('/sw.js').catch(() => {
      /* An unsupported or blocked worker just means no offline cache - the site works without it. */
    });
  });
}

// Shared styles must be in the entry CSS for prerendered public pages without JavaScript - and,
// since the public page components are now lazy chunks, so must every stylesheet those
// prerendered pages rely on: Vite would otherwise emit them with the chunk, and the static HTML
// would render unstyled until the JavaScript arrived. The prerender step inlines this entry CSS
// into every page's <head>.
import './pages/app/UpdatesPage.css';
import './pages/app/DetailPage.css';
import './components/layout/layout.css';
import './pages/compare/ComparePage.css';
import './pages/PublicPage.css';
import './pages/learn/LessonArticlePage.css';
import './pages/exams/ExamHub.css';
import './pages/exams/ExamDirectory.css';
import './components/layout/PublicContentLayout.css';
