// Builds the extra exam-hub sections - the syllabus subjects in short and practice-question links per section - from
// data that is already published and signed off: the syllabus pages (examSyllabi.mjs) and the /q/ question topics
// (questionTopics.mjs). scripts/gen-exam-hub-extras.mjs writes the result to src/data/examHubExtras.mjs, which the hub
// page imports instead of the 250 KB syllabus module; scripts/check-public-pages.mjs fails the build if it is stale.
//
// Pay is deliberately not carried over from the job-profile pages: their figures have no verification date, and the
// hub prints a number only with its official document and the date it was last checked (src/lib/examHub.mjs).
import { EXAM_SYLLABI } from '../data/examSyllabi.mjs';
import { QUESTION_TOPICS } from '../data/questionTopics.mjs';
import { HUB_EXAM_IDS } from '../data/examHubExams.mjs';

export const MAX_TOPICS_PER_GROUP = 8;

// The state GK topic for a state exam.
const STATE_GK = {
  up_police: 'UP_STATE_GK', uppsc: 'UP_STATE_GK',
  bihar_police: 'BIHAR_STATE_GK', bpsc: 'BIHAR_STATE_GK',
  mp_police: 'MP_STATE_GK', mppsc: 'MP_STATE_GK',
  rajasthan_police: 'RAJASTHAN_STATE_GK', rpsc: 'RAJASTHAN_STATE_GK',
  upsssc_pet: 'UP_STATE_GK', bssc_inter: 'BIHAR_STATE_GK', rajasthan_patwari: 'RAJASTHAN_STATE_GK', haryana_cet: 'HARYANA_STATE_GK',
};

// Which question subjects (QUESTION_TOPICS[*].subject) practise a syllabus subject, matched on its English name.
// One syllabus subject can match several ("Reasoning & Computer Aptitude"). "General" alone is not a cue: it also
// starts "General Intelligence", "General Hindi" and "General Mathematics".
const GROUP_RULES = [
  ['Pedagogy', /pedagog|child development/i],
  ['Quantitative Aptitude', /quant|numerical|mathemat|arithmetic|data analysis/i],
  ['Reasoning', /reason|intelligence|\bmental\b|logical|\biq\b|aptitude test/i],
  ['English', /english/i],
  ['General Studies', /awareness|general (?:knowledge|studies)|social|history|geograph|polity|econom|science|culture|environment|current affairs/i],
  ['General Awareness', /banking|financial/i],
  ['Computer Knowledge', /computer/i],
];
// Papers no topic practises: Hindi language, essays, optional subjects, language papers, trade and engineering papers.
const NO_PRACTICE = /hindi|essay|optional subject|language i\b|trade syllabus|engineering/i;

/** Question subjects that practise this syllabus subject, in GROUP_RULES order. */
export function practiceGroupsFor(subjectNameEn) {
  if (NO_PRACTICE.test(subjectNameEn) && !/english/i.test(subjectNameEn)) return [];
  return GROUP_RULES.filter(([, pattern]) => pattern.test(subjectNameEn)).map(([group]) => group);
}

// Practice groups [{ group, keys }] for an exam: question subjects in the order its syllabus first needs them (a state
// exam's own GK just before General Studies), each with its largest topics. Names and counts are looked up per language
// in EXAM_HUB_TOPICS at render time, so the module carries each topic once rather than once per exam and language.
function practiceFor(examId, syllabusEn) {
  const groups = [];
  for (const subject of syllabusEn.subjects) {
    for (const group of practiceGroupsFor(subject.name)) {
      if (group === 'General Studies' && STATE_GK[examId] && !groups.includes('State GK')) groups.push('State GK');
      if (!groups.includes(group)) groups.push(group);
    }
  }
  return groups.map((group) => ({
    group,
    keys: Object.entries(QUESTION_TOPICS)
      .filter(([key, t]) => t.en.count > 0 && (group === 'State GK' ? key === STATE_GK[examId] : t.subject === group))
      .sort((a, b) => b[1].en.count - a[1].en.count || a[1].en.name.localeCompare(b[1].en.name))
      .slice(0, MAX_TOPICS_PER_GROUP)
      .map(([key]) => key),
  })).filter((g) => g.keys.length > 0);
}

export function buildExamHubExtras() {
  const extras = {};
  for (const examId of HUB_EXAM_IDS) {
    const slug = examId.replace(/_/g, '-');
    const syllabus = EXAM_SYLLABI.find((e) => e.slug === slug);
    extras[examId] = {
      syllabus: syllabus
        ? {
            officialUrl: syllabus.officialUrl,
            ...Object.fromEntries(['en', 'hi'].map((lang) => [lang, syllabus[lang].subjects.map((s) => ({ name: s.name, body: s.body }))])),
          }
        : null,
      practice: syllabus ? practiceFor(examId, syllabus.en) : [],
    };
  }
  // Every topic a practice group links to: { slug, en: { name, count }, hi: { name, count } }.
  const topics = {};
  for (const entry of Object.values(extras)) {
    for (const { keys } of entry.practice) for (const key of keys) topics[key] ??= (({ slug, en, hi }) => ({ slug, en, hi }))(QUESTION_TOPICS[key]);
  }
  return { extras, topics };
}

/** The module text scripts/gen-exam-hub-extras.mjs writes; check:public compares it with the committed file. */
export function examHubExtrasSource({ extras, topics } = buildExamHubExtras()) {
  return [
    '// GENERATED by scripts/gen-exam-hub-extras.mjs from examSyllabi.mjs and questionTopics.mjs - do not hand-edit.',
    `export const EXAM_HUB_EXTRAS = ${JSON.stringify(extras)};`,
    `export const EXAM_HUB_TOPICS = ${JSON.stringify(topics)};`,
    '',
  ].join('\n');
}
