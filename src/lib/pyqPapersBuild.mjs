// Turns the server's PYQ seed files into the website's solved-paper data (scripts/gen-pyq-pages.mjs writes it).
import { EXAM_NAMES } from './examNames.mjs';

export const slugify = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const MONTHS = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec'];

/** "CGL 2024 Tier-I", 2024-09-09, "Shift 1" -> "cgl-2024-tier-i-9-sep-2024-shift-1". */
export function pyqPaperSlug({ paper, date, shift }) {
  const [y, m, d] = date.split('-');
  return slugify(`${paper} ${Number(d)} ${MONTHS[Number(m) - 1]} ${y} ${shift}`);
}

/** "SSC CGL" + "CGL 2024 Tier-I" -> "SSC CGL 2024 Tier-I" (the paper name repeats the exam's last word). */
export function pyqDisplayName(examId, paper) {
  const exam = EXAM_NAMES[examId] ?? examId;
  const first = paper.split(/\s+/)[0];
  return exam.split(/\s+/).at(-1) === first ? `${exam} ${paper.slice(first.length).trim()}` : `${exam} ${paper}`;
}

export function buildPyqPapers(files, topicNames = {}) {
  return files
    .map((f) => ({
      examId: f.examId,
      paper: f.paper,
      displayName: pyqDisplayName(f.examId, f.paper),
      date: f.date,
      shift: f.shift,
      year: f.year,
      sourceUrl: f.sourceUrl,
      marksPerQuestion: f.marksPerQuestion ?? 1,
      negativeMarksPerWrong: f.negativeMarksPerWrong ?? 0.25,
      // Set when marking differs by section (SSC MTS: none in Session-I, -1 in Session-II); the page prints it instead.
      ...(f.markingNote ? { markingNote: f.markingNote } : {}),
      questionsInPaper: f.questionsInPaper ?? null,
      // The official cut-off of this paper's own cycle, when the seed file names one (server prisma/seed-data/pyq/README.md).
      ...(f.cutoff ? { cutoff: { section: f.cutoff.section, cycleLabel: f.cutoff.cycleLabel } } : {}),
      slug: pyqPaperSlug(f),
      questions: f.questions
        .filter((q) => !q.cancelled)
        .map((q) => ({
          section: q.section ?? null,
          number: q.number ?? null,
          topicKey: q.topicKey,
          topicName: topicNames[q.topicKey] ?? q.topicKey,
          languageCode: q.languageCode,
          text: q.text,
          options: q.options,
          correctOptionIndex: q.correctOptionIndex,
          explanation: q.explanation,
        })),
    }))
    .sort((a, b) => a.examId.localeCompare(b.examId) || b.date.localeCompare(a.date) || a.shift.localeCompare(b.shift));
}

/** The small module the exam hub imports: which papers have a solved-paper page, keyed as the server's summary names them. */
export function pyqIndexSource(papers) {
  const index = papers.map((p) => ({ examId: p.examId, paper: p.paper, date: p.date, shift: p.shift, slug: p.slug }));
  return `// GENERATED by scripts/gen-pyq-pages.mjs - do not hand-edit; re-run the script.\nexport const PYQ_PAPER_INDEX = ${JSON.stringify(index)};\n`;
}
