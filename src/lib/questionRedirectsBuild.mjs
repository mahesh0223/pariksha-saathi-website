// Builds src/data/questionRedirects.mjs - where each question now sits on its topic list - from the same data and
// grouping the prerender uses for the lists (groupByTopic, topicPageOf), so the redirects cannot point at the wrong
// page. Written by scripts/gen-question-redirects.mjs; check:public compares the committed file with this output.
import { readFileSync } from 'node:fs';
import { QUESTION_TOPICS } from '../data/questionTopics.mjs';
import { groupByTopic, topicPageOf } from './questionPage.mjs';

export function questionRedirectsSource() {
  const topics = [];
  const topicIndex = new Map();
  const map = { topics, en: {}, hi: {} };
  for (const lang of ['en', 'hi']) {
    const questions = JSON.parse(readFileSync(new URL(`../data/question-pages/${lang}.json`, import.meta.url), 'utf8'));
    for (const [topicKey, list] of groupByTopic(questions)) {
      const slug = QUESTION_TOPICS[topicKey].slug;
      if (!topicIndex.has(slug)) {
        topicIndex.set(slug, topics.length);
        topics.push(slug);
      }
      list.forEach((q, i) => {
        map[lang][q.slug] = `${topicIndex.get(slug)}.${topicPageOf(i)}`;
      });
    }
  }
  return `// GENERATED by scripts/gen-question-redirects.mjs - do not hand-edit; re-run the script.
// Old one-question page slug -> "topic index.page" on its topic list (see src/lib/questionRedirects.mjs).
export const QUESTION_REDIRECTS = ${JSON.stringify(map)};
`;
}
